"""Build a self-contained gzip asset table; no separate filesystem upload."""
import gzip
from pathlib import Path

Import("env")

root = Path(env.subst("$PROJECT_DIR"))
required = [root / 'assets' / 'fonts' / (name + '.ttf')
            for name in ('ui-bold', 'ui-regular', 'clock')]
if any(not font.is_file() for font in required):
    raise RuntimeError('Font assets are missing. Run python scripts/prepare_face_fonts.py; see README.md.')
if not (root / 'include' / 'network_config.h').is_file():
    raise RuntimeError('Copy include/network_config.example.h to include/network_config.h and set Wi-Fi credentials.')
# LVGL 9.4 truncates 255*255 to 254 for vector alpha. That darkens solid
# colors by one, changing an entire RGB565 color step (e.g. cream blue 224).
# Keep this narrow, version-pinned correction reproducible after pio clean.
vector_source = root / '.pio' / 'libdeps' / env.subst('$PIOENV') / 'lvgl' / 'src' / 'draw' / 'sw' / 'lv_draw_sw_vector.c'
if vector_source.exists():
    source = vector_source.read_text(encoding='utf-8')
    original = 'color->a = LV_OPA_MIX2(c->alpha, opa);'
    corrected = 'color->a = ((uint32_t)c->alpha * opa + 127) / 255;'
    if original in source:
        vector_source.write_text(source.replace(original, corrected), encoding='utf-8')
    elif corrected not in source:
        raise RuntimeError('LVGL vector alpha patch no longer matches; review dependency version')

# Preserve fractional TrueType advances instead of accumulating LVGL's rounded
# per-character widths. This bridge uses the pinned tiny_ttf implementation.
ttf_source = root / '.pio' / 'libdeps' / env.subst('$PIOENV') / 'lvgl' / 'src' / 'libs' / 'tiny_ttf' / 'lv_tiny_ttf.c'
if ttf_source.exists():
    source = ttf_source.read_text(encoding='utf-8')
    marker = 'void lv_tiny_ttf_set_size(lv_font_t * font, int32_t font_size)'
    if 'float desk_face_ttf_advance(' not in source:
        if marker not in source:
            raise RuntimeError('LVGL tiny_ttf metrics bridge no longer matches')
        bridge = '''float desk_face_ttf_advance(const lv_font_t * font, uint32_t code, uint32_t next)
{
    const ttf_font_desc_t * dsc = (const ttf_font_desc_t *)font->dsc;
    int width, bearing;
    stbtt_GetCodepointHMetrics(&dsc->info, code, &width, &bearing);
    int kern = next ? stbtt_GetCodepointKernAdvance(&dsc->info, code, next) : 0;
    return dsc->scale * (width + kern);
}

'''
        ttf_source.write_text(source.replace(marker, bridge + marker), encoding='utf-8')
generated = root / ".pio" / "generated"
generated.mkdir(parents=True, exist_ok=True)
assets = [
    ("/", "text/html; charset=utf-8", "DeskFriend_index.html"),
    ("/device_monitor.mjs", "text/javascript; charset=utf-8", "assets/device_monitor.mjs"),
    ("/vendor/three.module.min.js", "text/javascript; charset=utf-8", "assets/vendor/three.module.min.js"),
    ("/vendor/OrbitControls.js", "text/javascript; charset=utf-8", "assets/vendor/OrbitControls.js"),
]
fonts = [('bold', 'ui-bold'), ('regular', 'ui-regular'), ('clock', 'clock')]
font_header = ['#pragma once\n#include <stddef.h>\n']
font_data = ['// Generated font data, shared between HTTP and LVGL.\n']
for symbol, name in fonts:
    data = (root / 'assets' / 'fonts' / (name + '.ttf')).read_bytes()
    font_header.append('extern const unsigned char face_font_%s[];\nconstexpr size_t face_font_%s_size = %d;\n' % (symbol, symbol, len(data)))
    font_data.append('const unsigned char face_font_%s[] = {\n' % symbol)
    for offset in range(0, len(data), 24):
        font_data.append(','.join(map(str, data[offset:offset + 24])) + ',\n')
    font_data.append('};\n')
for name, content in [('face_fonts.h', ''.join(font_header)), ('font_data.inc', ''.join(font_data))]:
    target = generated / name
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        target.write_text(content, encoding='utf-8')
parts = ["// Generated by scripts/embed_assets.py. Do not edit.\n#pragma once\n#include \"face_fonts.h\"\n",
         "struct WebAsset { const char* uri; const char* type; const unsigned char* data; size_t size; bool gzip; };\n"]
for index, (_, _, source) in enumerate(assets):
    data = gzip.compress((root / source).read_bytes(), compresslevel=9, mtime=0)
    parts.append("static const unsigned char asset_%d[] = {\n" % index)
    for offset in range(0, len(data), 24):
        parts.append(",".join(str(value) for value in data[offset:offset + 24]) + ",\n")
    parts.append("};\n")
parts.append("static const WebAsset kWebAssets[] = {\n")
for index, (uri, mime, _) in enumerate(assets):
    parts.append('{"%s", "%s", asset_%d, sizeof(asset_%d), true},\n' % (uri, mime, index, index))
for symbol, name in fonts:
    parts.append('{"/fonts/%s.ttf", "font/ttf", face_font_%s, face_font_%s_size, false},\n' % (name, symbol, symbol))
parts.append("};\n")
output = generated / "web_assets.h"
content = "".join(parts)
if not output.exists() or output.read_text(encoding="utf-8") != content:
    output.write_text(content, encoding="utf-8")
env.Append(CPPPATH=[str(generated)])
